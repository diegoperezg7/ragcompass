"""Render a :class:`Report` as JSON, Markdown, YAML or a terminal view."""

from __future__ import annotations

from typing import Any

import yaml
from rich.console import Console, Group
from rich.panel import Panel
from rich.table import Table
from rich.text import Text

from ragcompass.models import Report, SimulationResult
from ragcompass.rules import human_bytes

ACCENT = "#8B7CF6"


def to_json(report: Report) -> str:
    return report.model_dump_json(indent=2)


def to_yaml(report: Report) -> str:
    header = "# RAG configuration generated by ragcompass. Reasons: ragcompass analyze --md\n"
    return header + yaml.safe_dump(report.config, sort_keys=False, allow_unicode=True)


def format_value(value: Any) -> str:
    if isinstance(value, bool):
        return "yes" if value else "no"
    if isinstance(value, dict):
        return ", ".join(f"{k} {v}" for k, v in value.items())
    if isinstance(value, list):
        return ", ".join(str(v) for v in value)
    if isinstance(value, int):
        return f"{value:,}"
    return str(value)


def chosen_rows(report: Report) -> list[SimulationResult]:
    """Simulation rows at the recommended size of each group, best first."""
    rows = []
    for rec in report.recommendations:
        if not rec.key.startswith("chunking."):
            continue
        group = rec.key.split(".", 1)[1]
        size = rec.value["size"]
        group_rows = [s for s in report.simulations if s.group == group and s.size == size]
        rows.extend(sorted(group_rows, key=lambda s: (s.damage, s.strategy, s.overlap)))
    return rows


def _md_table(headers: list[str], rows: list[list[Any]]) -> str:
    out = ["| " + " | ".join(headers) + " |", "|" + "|".join("---" for _ in headers) + "|"]
    out += ["| " + " | ".join(str(c).replace("|", "\\|") for c in row) + " |" for row in rows]
    return "\n".join(out)


def to_markdown(report: Report) -> str:
    s = report.summary
    parts = [
        f"# ragcompass report: {s.root}",
        "",
        f"{s.analysed} of {s.files} files analysed, {s.tokens:,} tokens ({s.tokenizer}), "
        f"{s.pages} pages, languages: {', '.join(s.languages) or 'n/a'}.",
        "",
        "## Recommendations",
        "",
        _md_table(
            ["Setting", "Value", "Why"],
            [[r.key, format_value(r.value), r.reason] for r in report.recommendations],
        ),
        "",
        "## Documents",
        "",
        _md_table(
            ["File", "Kind", "Pages", "Tokens", "Lang", "Headings", "Tables", "Lists", "Images", "IDs/1k"],
            [
                [
                    d.path,
                    d.kind.value,
                    d.pages or "",
                    d.tokens,
                    d.language or "",
                    d.headings,
                    d.tables,
                    d.list_items,
                    d.images,
                    d.identifiers.per_1k_tokens,
                ]
                for d in report.documents
            ],
        ),
        "",
        "## Chunking simulation (recommended size)",
        "",
        _md_table(
            [
                "Group",
                "Strategy",
                "Size",
                "Overlap",
                "Chunks",
                "p50",
                "p95",
                "Sentence cuts",
                "Table cuts",
                "Orphan headings",
                "Tiny",
                "Damage",
            ],
            [
                [
                    r.group,
                    r.strategy,
                    r.size,
                    r.overlap,
                    r.chunks,
                    r.tokens.p50,
                    r.tokens.p95,
                    f"{r.sentence_cut_pct}%",
                    f"{r.table_cut_pct}%",
                    f"{r.orphan_heading_pct}%",
                    f"{r.tiny_pct}%",
                    r.damage,
                ]
                for r in chosen_rows(report)
            ],
        ),
        "",
        "## Index size",
        "",
        _md_table(
            ["Dimension", "Vectors", "float32", "int8", "HNSW graph"],
            [
                [
                    i.dimension,
                    i.vectors,
                    human_bytes(i.float32_bytes),
                    human_bytes(i.int8_bytes),
                    human_bytes(i.hnsw_overhead_bytes),
                ]
                for i in report.index
            ],
        ),
        "",
        "## Embedding cost",
        "",
        _md_table(
            ["Model", "USD / 1M tokens", "Tokens", "USD"],
            [[c.model, c.usd_per_million, f"{c.tokens:,}", f"{c.usd:.4f}"] for c in report.costs],
        ),
    ]
    if report.llm_summary:
        parts += ["", "## Summary", "", report.llm_summary]
    return "\n".join(parts) + "\n"


def render(report: Report, console: Console | None = None, verbose: bool = False) -> None:
    console = console or Console()
    s = report.summary
    head = Text.assemble(
        ("ragcompass ", f"bold {ACCENT}"),
        (f"{s.root}  ", "bold"),
        (
            f"{s.analysed}/{s.files} files · {s.tokens:,} tokens · {s.pages} pages · "
            f"{', '.join(s.languages) or 'n/a'} · {s.tokenizer}",
            "dim",
        ),
    )

    docs = Table(box=None, header_style="bold", pad_edge=False, expand=False)
    for column in ("File", "Kind", "Pages", "Tokens", "Lang", "Struct", "Img", "IDs/1k"):
        docs.add_column(column, justify="right" if column in ("Pages", "Tokens", "Img", "IDs/1k") else "left")
    for d in report.documents:
        struct = f"{d.headings}h {d.tables}t {d.list_items}l"
        kind = Text(d.kind.value, style="yellow" if "scanned" in d.kind.value or d.error else "")
        docs.add_row(
            d.path,
            kind,
            str(d.pages or ""),
            f"{d.tokens:,}",
            d.language or "",
            struct,
            str(d.images),
            f"{d.identifiers.per_1k_tokens}",
        )

    recs = Table(box=None, header_style="bold", show_lines=False, expand=True, pad_edge=False)
    recs.add_column("Setting", style=ACCENT, no_wrap=True)
    recs.add_column("Value", style="bold", max_width=34)
    recs.add_column("Why", style="dim", ratio=1)
    for r in report.recommendations:
        recs.add_row(r.key, format_value(r.value), r.reason)

    sims = Table(box=None, header_style="bold", pad_edge=False)
    for column in (
        "Group",
        "Strategy",
        "Size",
        "Ovl",
        "Chunks",
        "p50",
        "p95",
        "Sentence",
        "Table",
        "Orphan",
        "Tiny",
        "Damage",
    ):
        sims.add_column(column, justify="left" if column in ("Group", "Strategy") else "right")
    rows = report.simulations if verbose else chosen_rows(report)
    best = {
        (r.key.split(".", 1)[1], r.value["strategy"], r.value["overlap"])
        for r in report.recommendations
        if r.key.startswith("chunking.")
    }
    for r in rows:
        style = f"bold {ACCENT}" if (r.group, r.strategy, r.overlap) in best else ""
        sims.add_row(
            r.group,
            r.strategy,
            str(r.size),
            str(r.overlap),
            str(r.chunks),
            str(r.tokens.p50),
            str(r.tokens.p95),
            f"{r.sentence_cut_pct}%",
            f"{r.table_cut_pct}%",
            f"{r.orphan_heading_pct}%",
            f"{r.tiny_pct}%",
            f"{r.damage}",
            style=style,
        )

    index = Table(box=None, header_style="bold", pad_edge=False)
    for column in ("Dim", "Vectors", "float32", "int8", "HNSW"):
        index.add_column(column, justify="right")
    for i in report.index:
        index.add_row(
            str(i.dimension),
            f"{i.vectors:,}",
            human_bytes(i.float32_bytes),
            human_bytes(i.int8_bytes),
            human_bytes(i.hnsw_overhead_bytes),
        )

    console.print(Panel(head, border_style=ACCENT, expand=True))
    console.print(Panel(docs, title="Documents", title_align="left", border_style="grey35"))
    console.print(Panel(sims, title="Chunking simulation", title_align="left", border_style="grey35"))
    console.print(Panel(recs, title="Recommendations", title_align="left", border_style=ACCENT))
    console.print(Panel(Group(index), title="Index size", title_align="left", border_style="grey35"))
    if report.llm_summary:
        console.print(
            Panel(report.llm_summary, title="Summary (LLM)", title_align="left", border_style="grey35")
        )


def dumps(report: Report, fmt: str) -> str:
    if fmt == "json":
        return to_json(report)
    if fmt == "md":
        return to_markdown(report)
    if fmt == "yaml":
        return to_yaml(report)
    raise ValueError(f"unknown format {fmt!r}")
