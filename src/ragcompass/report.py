"""Render a :class:`Report` as JSON, Markdown, YAML or a terminal view."""

from __future__ import annotations

from typing import Any

import yaml
from rich.console import Console, Group
from rich.panel import Panel
from rich.table import Table
from rich.text import Text

from ragcompass.messages import LANGUAGES, Formatter, label
from ragcompass.models import Report, SimulationResult

ACCENT = "#8B7CF6"


def localize(report: Report, lang: str) -> Report:
    """Set the language every reason is rendered in. All languages stay in ``reason_i18n``."""
    if lang not in LANGUAGES:
        raise ValueError(f"unknown language {lang!r}; choose one of: {', '.join(LANGUAGES)}")
    report.lang = lang
    for rec in report.recommendations:
        rec.reason = rec.reason_i18n.get(lang, rec.reason)
    return report


def to_json(report: Report) -> str:
    return report.model_dump_json(indent=2)


def to_yaml(report: Report) -> str:
    header = "# RAG configuration generated by ragcompass. Reasons: ragcompass analyze --md\n"
    return header + yaml.safe_dump(report.config, sort_keys=False, allow_unicode=True)


def format_value(value: Any, lang: str = "en") -> str:
    if value is None:
        return label("undecided", lang)
    if isinstance(value, bool):
        return label("yes" if value else "no", lang)
    if isinstance(value, dict):
        return ", ".join(f"{k} {v}" for k, v in value.items())
    if isinstance(value, list):
        return ", ".join(str(v) for v in value)
    if isinstance(value, int):
        return Formatter(lang).format_field(value, ",")
    return str(value)


def chosen_rows(report: Report) -> list[SimulationResult]:
    """Simulation rows at the recommended size of each group, best first."""
    rows = []
    for rec in report.recommendations:
        if not rec.key.startswith("chunking."):
            continue
        group = rec.key.split(".", 1)[1]
        size = rec.value["size"]
        group_rows = [s for s in report.simulations if s.group == group and s.size == size]
        rows.extend(sorted(group_rows, key=lambda s: (s.damage, s.strategy, s.overlap)))
    return rows


def _md_table(headers: list[str], rows: list[list[Any]]) -> str:
    out = ["| " + " | ".join(headers) + " |", "|" + "|".join("---" for _ in headers) + "|"]
    out += ["| " + " | ".join(str(c).replace("|", "\\|") for c in row) + " |" for row in rows]
    return "\n".join(out)


def _summary(report: Report) -> str:
    s = report.summary
    return label(
        "summary",
        report.lang,
        analysed=s.analysed,
        files=s.files,
        tokens=s.tokens,
        tokenizer=s.tokenizer,
        pages=s.pages,
        languages=", ".join(s.languages) or "n/a",
    )


def _metric_cells(r: SimulationResult, lang: str) -> list[str]:
    num = Formatter(lang).format_field
    pcts = (r.sentence_cut_pct, r.table_cut_pct, r.orphan_heading_pct, r.code_cut_pct, r.tiny_pct)
    return [num(v, "") + "%" for v in pcts] + [num(r.damage, "")]


SIMULATION_KEYS = ("group", "strategy", "size", "overlap", "chunks", "p50", "p95")
METRIC_KEYS = ("sentence", "table", "orphan", "code", "tiny", "damage")


def to_markdown(report: Report) -> str:
    lang = report.lang
    num = Formatter(lang).format_field

    def t(key: str) -> str:
        return key if key in ("p50", "p95") else label(key, lang)

    doc_keys = ("file", "kind", "pages", "tokens", "lang", "headings", "tables", "lists", "images", "ids")
    parts = [
        "<!-- generated by ragcompass -->",
        f"# {t('report')}: {report.summary.root}",
        "",
        _summary(report),
        "",
        f"## {t('recommendations')}",
        "",
        _md_table(
            [t("setting"), t("value"), t("basis"), t("why")],
            [[r.key, format_value(r.value, lang), t(r.basis), r.reason] for r in report.recommendations],
        ),
        "",
        f"## {t('documents')}",
        "",
        _md_table(
            [t(k) for k in doc_keys],
            [
                [
                    d.path,
                    d.kind.value,
                    d.pages or "",
                    num(d.tokens, ","),
                    d.language or "",
                    d.headings,
                    d.tables,
                    d.list_items,
                    d.images,
                    num(d.identifiers.per_1k_tokens, ""),
                ]
                for d in report.documents
            ],
        ),
        "",
        f"## {t('simulation')}",
        "",
        _md_table(
            [t(k) for k in SIMULATION_KEYS + METRIC_KEYS],
            [
                [r.group, r.strategy, r.size, r.overlap, r.chunks, r.tokens.p50, r.tokens.p95]
                + _metric_cells(r, lang)
                for r in chosen_rows(report)
            ],
        ),
        "",
        f"## {t('index')}",
        "",
        _md_table(
            [t("dimension"), t("vectors"), "float32", "int8", t("hnsw")],
            [
                [
                    i.dimension,
                    num(i.vectors, ","),
                    num(i.float32_bytes, "bytes"),
                    num(i.int8_bytes, "bytes"),
                    num(i.hnsw_overhead_bytes, "bytes"),
                ]
                for i in report.index
            ],
        ),
        "",
        f"## {t('cost')}",
        "",
        _md_table(
            [t("model"), t("per_million"), t("tokens"), t("usd")],
            [
                [c.model, num(c.usd_per_million, ".2f"), num(c.tokens, ","), num(c.usd, ".4f")]
                for c in report.costs
            ],
        ),
    ]
    if report.bench:
        parts += ["", *bench_markdown(report)]
    if report.llm_summary:
        parts += ["", f"## {t('summary_llm')}", "", report.llm_summary]
    return "\n".join(parts) + "\n"


def _interval(value: dict, lang: str) -> str:
    num = Formatter(lang).format_field
    separator = "; " if lang == "es" else ", "
    return f"{num(round(value['mean'], 3), '')} [{num(round(value['ci'][0], 3), '')}{separator}{num(round(value['ci'][1], 3), '')}]"


def _bench_rows(bench: dict, lang: str) -> list[list[str]]:
    num = Formatter(lang).format_field
    return [
        [
            c["label"] + (" *" if c["recommended"] else ""),
            str(c["chunks"]),
            _interval(c["recall_at_k"], lang),
            _interval(c.get("recall_at_budget") or c["recall_at_k"], lang),
            _interval(c["mrr"], lang),
            _interval(c["ndcg"], lang),
            num(round(c["index_ms"], 1), ""),
            num(round(c["query_ms"]["mean"], 2), ""),
        ]
        for c in sorted(bench["configs"], key=lambda c: -c["ndcg"]["mean"])
    ]


def _bench_summary(bench: dict, lang: str) -> str:
    return label(
        "bench_summary",
        lang,
        queries=bench["queries"],
        mode=bench["mode"],
        seed=bench["seed"],
        k=bench["k"],
        retrievers=", ".join(bench["retrievers"]),
        model=bench["dense_model"] or "-",
    )


def _shown_warnings(bench: dict) -> list[str]:
    """Warnings minus the synthetic-query one, which the translated note already states."""
    return [w for w in bench["warnings"] if not w.startswith("synthetic queries")]


def _bench_queries(bench: dict, lang: str) -> str:
    num = Formatter(lang).format_field
    overlap = bench.get("lexical_overlap") or {}
    return label(
        "bench_queries",
        lang,
        kinds=", ".join(f"{kind} {count}" for kind, count in bench.get("query_kinds", {}).items()),
        overlap=num(overlap.get("mean", 0.0), ""),
        by_kind=", ".join(f"{kind} {num(value, '')}" for kind, value in overlap.get("by_kind", {}).items()),
    )


def bench_markdown(report: Report) -> list[str]:
    lang, bench = report.lang, report.bench
    k = bench["k"]
    headers = [
        label("config", lang),
        label("chunks", lang),
        label("recall_k", lang, k=k),
        label("recall_budget", lang, budget=bench.get("budget_tokens", 1024)),
        label("mrr", lang),
        label("ndcg_k", lang, k=k),
        label("index_ms", lang),
        label("query_ms", lang),
    ]
    lines = [
        f"## {label('benchmark', lang)}",
        "",
        _bench_summary(bench, lang),
        "",
        _bench_queries(bench, lang),
        "",
    ]
    if bench["mode"] != "file":
        lines += [f"> {label('bench_note', lang)}", ""]
    lines += [_md_table(headers, _bench_rows(bench, lang)), ""]
    lines += [f"### {label('decisions', lang)}", ""]
    for d in bench["decisions"]:
        state = label("changed" if d["changed"] else "confirmed", lang)
        lines.append(
            f"- **{d['key']}** ({label(d['basis'], lang)}, {state}): {d['reason_i18n'].get(lang, d['reason'])}"
        )
    for warning in _shown_warnings(bench):
        lines.append(f"- {label('warning', lang)}: {warning}")
    return lines


def render_bench(report: Report, console: Console) -> None:
    lang, bench = report.lang, report.bench
    k = bench["k"]
    table = Table(box=None, header_style="bold", pad_edge=False)
    headers = [
        label("config", lang),
        label("chunks", lang),
        label("recall_k", lang, k=k),
        label("recall_budget", lang, budget=bench.get("budget_tokens", 1024)),
        label("mrr", lang),
        label("ndcg_k", lang, k=k),
        label("index_ms", lang),
        label("query_ms", lang),
    ]
    for i, header in enumerate(headers):
        table.add_column(header, justify="left" if i == 0 else "right", no_wrap=True)
    for row in _bench_rows(bench, lang):
        table.add_row(*row, style=f"bold {ACCENT}" if row[0].startswith(bench["winner"]["label"]) else "")
    decisions = Table(box=None, show_header=False, pad_edge=False, expand=True)
    decisions.add_column(style=ACCENT, no_wrap=True)
    decisions.add_column(style="bold", no_wrap=True)
    decisions.add_column(style="dim", ratio=1)
    for d in bench["decisions"]:
        state = label("changed" if d["changed"] else "confirmed", lang)
        decisions.add_row(
            d["key"], f"{label(d['basis'], lang)}, {state}", d["reason_i18n"].get(lang, d["reason"])
        )
    body = [Text(_bench_summary(bench, lang), style="dim"), Text(_bench_queries(bench, lang), style="dim")]
    if bench["mode"] != "file":
        body.append(Text(label("bench_note", lang), style="yellow"))
    body += [table, Text(""), decisions]
    body += [Text(f"{label('warning', lang)}: {w}", style="yellow") for w in _shown_warnings(bench)]
    console.print(
        Panel(Group(*body), title=label("benchmark", lang), title_align="left", border_style=ACCENT)
    )


def render(report: Report, console: Console | None = None, verbose: bool = False) -> None:
    console = console or Console()
    lang = report.lang
    num = Formatter(lang).format_field

    def t(key: str) -> str:
        return key if key in ("p50", "p95") else label(key, lang)

    head = Text.assemble(
        ("ragcompass ", f"bold {ACCENT}"),
        (f"{report.summary.root}  ", "bold"),
        (_summary(report), "dim"),
    )

    docs = Table(box=None, header_style="bold", pad_edge=False, expand=False)
    numeric = {"pages", "tokens", "images", "ids"}
    for key in ("file", "kind", "pages", "tokens", "lang", "structure", "images", "ids"):
        docs.add_column(t(key), justify="right" if key in numeric else "left")
    for d in report.documents:
        struct = f"{d.headings}h {d.tables}t {d.list_items}l"
        kind = Text(d.kind.value, style="yellow" if "scanned" in d.kind.value or d.error else "")
        docs.add_row(
            d.path,
            kind,
            str(d.pages or ""),
            num(d.tokens, ","),
            d.language or "",
            struct,
            str(d.images),
            num(d.identifiers.per_1k_tokens, ""),
        )

    recs = Table(box=None, header_style="bold", show_lines=False, expand=True, pad_edge=False)
    recs.add_column(t("setting"), style=ACCENT, no_wrap=True)
    recs.add_column(t("value"), style="bold", max_width=34)
    recs.add_column(t("basis"), no_wrap=True)
    recs.add_column(t("why"), style="dim", ratio=1)
    for r in report.recommendations:
        recs.add_row(r.key, format_value(r.value, lang), t(r.basis), r.reason)

    sims = Table(box=None, header_style="bold", pad_edge=False)
    for key in SIMULATION_KEYS + METRIC_KEYS:
        sims.add_column(t(key), justify="left" if key in ("group", "strategy") else "right")
    rows = report.simulations if verbose else chosen_rows(report)
    best = {
        (r.key.split(".", 1)[1], r.value["strategy"], r.value["overlap"])
        for r in report.recommendations
        if r.key.startswith("chunking.")
    }
    for r in rows:
        style = f"bold {ACCENT}" if (r.group, r.strategy, r.overlap) in best else ""
        sims.add_row(
            r.group,
            r.strategy,
            str(r.size),
            str(r.overlap),
            str(r.chunks),
            str(r.tokens.p50),
            str(r.tokens.p95),
            *_metric_cells(r, lang),
            style=style,
        )

    index = Table(box=None, header_style="bold", pad_edge=False)
    for column in (t("dimension"), t("vectors"), "float32", "int8", "HNSW"):
        index.add_column(column, justify="right")
    for i in report.index:
        index.add_row(
            str(i.dimension),
            num(i.vectors, ","),
            num(i.float32_bytes, "bytes"),
            num(i.int8_bytes, "bytes"),
            num(i.hnsw_overhead_bytes, "bytes"),
        )

    console.print(Panel(head, border_style=ACCENT, expand=True))
    console.print(Panel(docs, title=t("documents"), title_align="left", border_style="grey35"))
    console.print(Panel(sims, title=t("simulation_short"), title_align="left", border_style="grey35"))
    console.print(Panel(recs, title=t("recommendations"), title_align="left", border_style=ACCENT))
    console.print(Panel(Group(index), title=t("index"), title_align="left", border_style="grey35"))
    if report.bench:
        render_bench(report, console)
    if report.llm_summary:
        console.print(
            Panel(report.llm_summary, title=t("summary_llm"), title_align="left", border_style="grey35")
        )
