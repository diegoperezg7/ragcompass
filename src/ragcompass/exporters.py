def _settings(report: Report) -> dict:
    recs = {r.key: r for r in report.recommendations}
    group = (
        "documents"
        if "chunking.documents" in recs
        else next((k.split(".", 1)[1] for k in recs if k.startswith("chunking.")), "documents")
    )
    chunking = recs.get(f"chunking.{group}")
    value = chunking.value if chunking else {"strategy": "recursive", "size": 512, "overlap": 0}
    retriever = recs["retrieval.retriever"].value if "retrieval.retriever" in recs else None
    retriever = retriever or (
        "hybrid" if recs.get("retrieval.hybrid_bm25") and recs["retrieval.hybrid_bm25"].value else "dense"
    )
    models = recs["embedding.dimension"].evidence.get("models") if "embedding.dimension" in recs else None
    model = next((m for m in models or [] if m in OLLAMA_MODELS), "nomic-embed-text")
    top_k = recs["retrieval.top_k"].value["final"] if "retrieval.top_k" in recs else 5
    reranker = recs["retrieval.reranker"].value if "retrieval.reranker" in recs else False
    measured = any(r.basis == "measured" for r in report.recommendations)
    lines = [f"chunking.{group}: {value['strategy']}, {value['size']} tokens, overlap {value['overlap']}"]
    for key in ("chunking.tables", "chunking.code"):
        if key in recs and key != f"chunking.{group}":
            v = recs[key].value
            lines.append(
                f"{key}: {v['strategy']}, {v['size']} tokens, overlap {v['overlap']} (split those files separately)"
            )
    lines.append(f"retriever: {retriever}, top-k {top_k}" + (f", rerank with {reranker}" if reranker else ""))
    lines.append(f"embeddings: {model} through Ollama (any embedding model works)")
    return {
        "root": report.summary.root,
        "basis": "measured" if measured else "rule-based",
        "summary": "\n".join(lines),
        "strategy": value["strategy"],
        "size": value["size"],
        "overlap": value["overlap"],
        "retriever": retriever,
        "top_k": top_k,
        "model": model,
    }


