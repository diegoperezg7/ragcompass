def _imports(target: str, strategy: str, retriever: str) -> tuple[str, str]:
    table = IMPORTS[target]
    entries = table["base"] + table[strategy] + table[retriever]
    by_module: dict[str, set[str]] = {}
    packages: list[str] = []
    for module, name, package in entries:
        if module:
            by_module.setdefault(module, set()).add(name)
        if package not in packages:
            packages.append(package)
    lines = [
        f"from {module} import {', '.join(sorted(names))}" for module, names in sorted(by_module.items())
    ]
    return "\n".join(lines), " ".join(packages)


FRAMEWORKS = {
    "langchain": (LANGCHAIN, LANGCHAIN_SPLIT, LANGCHAIN_RETRIEVER),
    "llamaindex": (LLAMAINDEX, LLAMAINDEX_SPLIT, LLAMAINDEX_RETRIEVER),
    "haystack": (HAYSTACK, HAYSTACK_SPLIT, HAYSTACK_RETRIEVER),
}


def render(target: str, values: dict) -> str:
    """Fill a framework page from settings: strategy, size, overlap, retriever, top_k, model..."""
    page, splits, retrievers = FRAMEWORKS[target]
    imports, packages = _imports(target, values["strategy"], values["retriever"])
    return Template(page).substitute(
        values,
        imports=imports,
        packages=packages,
        split=Template(splits[values["strategy"]]).substitute(values),
        retriever=Template(retrievers[values["retriever"]]).substitute(values),
    )


def export(report: Report, target: str) -> str:
    if target == "yaml":
        return to_yaml(report)
    if target not in FRAMEWORKS:
        raise ValueError(f"unknown target {target!r}; choose one of: {', '.join(TARGETS)}")
    return render(target, _settings(report))
