"""File type detection and structural extraction."""

from __future__ import annotations

import codecs
from dataclasses import dataclass, field
from pathlib import Path

from ragcompass.models import Block, DocKind

CODE_EXTENSIONS = {
    ".py",
    ".js",
    ".jsx",
    ".ts",
    ".tsx",
    ".java",
    ".kt",
    ".go",
    ".rs",
    ".rb",
    ".php",
    ".c",
    ".h",
    ".cc",
    ".cpp",
    ".hpp",
    ".cs",
    ".swift",
    ".scala",
    ".sql",
    ".sh",
}
IMAGE_EXTENSIONS = {".png", ".jpg", ".jpeg", ".gif", ".webp", ".tif", ".tiff", ".bmp"}
TEXT_EXTENSIONS = {".txt", ".rst", ".log"}
# Structured data files are text to embed, not source code; they are read without markdown rules.
DATA_EXTENSIONS = {".json", ".jsonl", ".yaml", ".yml", ".toml", ".xml"}
MARKDOWN_EXTENSIONS = {".md", ".markdown"}
HTML_EXTENSIONS = {".html", ".htm"}
IGNORED_NAMES = {".DS_Store"}
# Every output format of ragcompass carries one of these near the top, so a report or a
# ragcompass.yaml left inside the corpus is never analysed as a document.
OUTPUT_MARKERS = (b"generated by ragcompass", b'"generator": "ragcompass')
IGNORED_DIRS = {".git", "node_modules", ".venv", "__pycache__"}


@dataclass
class Extracted:
    kind: DocKind
    blocks: list[Block] = field(default_factory=list)
    pages: int | None = None
    scanned_pages: int = 0
    images: int = 0
    error: str | None = None
    warnings: list[str] = field(default_factory=list)


def detect_kind(path: Path) -> DocKind:
    ext = path.suffix.lower()
    if ext == ".pdf":
        return DocKind.PDF_TEXT  # refined to scanned or mixed after reading pages
    if ext == ".docx":
        return DocKind.DOCX
    if ext in MARKDOWN_EXTENSIONS:
        return DocKind.MARKDOWN
    if ext in HTML_EXTENSIONS:
        return DocKind.HTML
    if ext in (".csv", ".tsv"):
        return DocKind.CSV
    if ext in (".xlsx", ".xlsm"):
        return DocKind.XLSX
    if ext in CODE_EXTENSIONS:
        return DocKind.CODE
    if ext in TEXT_EXTENSIONS or ext in DATA_EXTENSIONS:
        return DocKind.TEXT
    if ext in IMAGE_EXTENSIONS:
        return DocKind.IMAGE
    return DocKind.UNSUPPORTED


def iter_files(root: Path) -> list[Path]:
    if root.is_file():
        return [root]
    files = []
    for path in sorted(root.rglob("*")):
        if not path.is_file() or path.name in IGNORED_NAMES:
            continue
        if any(part in IGNORED_DIRS or part.startswith(".") for part in path.relative_to(root).parts):
            continue
        if is_own_output(path):
            continue
        files.append(path)
    return files


def is_own_output(path: Path) -> bool:
    if path.suffix.lower() not in (".yaml", ".yml", ".json", ".md"):
        return False
    with path.open("rb") as handle:
        head = handle.read(512)
    return any(marker in head for marker in OUTPUT_MARKERS)


def extract(path: Path) -> Extracted:
    from ragcompass.ingest import docx, html, pdf, tabular, text

    kind = detect_kind(path)
    try:
        match kind:
            case DocKind.PDF_TEXT:
                return pdf.extract(path)
            case DocKind.DOCX:
                return docx.extract(path)
            case DocKind.HTML:
                return html.extract(path)
            case DocKind.CSV:
                return tabular.extract_csv(path)
            case DocKind.XLSX:
                return tabular.extract_xlsx(path)
            case DocKind.TEXT if path.suffix.lower() in DATA_EXTENSIONS:
                return Extracted(kind=kind, blocks=text.parse_plain(read_text(path)))
            case DocKind.MARKDOWN | DocKind.TEXT:
                return Extracted(kind=kind, blocks=text.parse_markdown(read_text(path)))
            case DocKind.CODE:
                return text.extract_code(path)
            case DocKind.IMAGE:
                return Extracted(kind=kind, images=1)
            case _:
                return Extracted(kind=kind)
    except Exception as exc:  # a broken file must not stop the whole corpus
        return Extracted(kind=kind, error=f"{type(exc).__name__}: {exc}")


def read_text(path: Path) -> str:
    raw = path.read_bytes()
    if raw.startswith((codecs.BOM_UTF32_LE, codecs.BOM_UTF32_BE)):
        return raw.decode("utf-32")
    if raw.startswith((codecs.BOM_UTF16_LE, codecs.BOM_UTF16_BE)):
        return raw.decode("utf-16")
    try:
        return raw.decode("utf-8-sig")  # also strips a UTF-8 BOM
    except UnicodeDecodeError:
        pass
    try:
        return raw.decode("cp1252")
    except UnicodeDecodeError:
        return raw.decode("latin-1")  # maps every byte, so it cannot fail
