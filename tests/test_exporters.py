import ast
import itertools
import os
import subprocess
from pathlib import Path

import pytest

from ragcompass.analyze import analyze
from ragcompass.exporters import FRAMEWORKS, TARGETS, export, render
from ragcompass.tokens import RegexTokenizer
from tests.conftest import CORPUS

STRATEGIES = ("heading", "recursive", "fixed", "page", "row")
RETRIEVERS = ("bm25", "dense", "hybrid")
RUNNER = Path(__file__).parent / "snippets" / "run_snippet.py"
# An interpreter with LangChain, LlamaIndex and Haystack installed; the runtime test is skipped without it.
SNIPPET_PYTHON = os.environ.get("RAGCOMPASS_SNIPPET_PYTHON")


def values(strategy, retriever):
    return {
        "root": "test",
        "basis": "rule-based",
        "summary": "test",
        "strategy": strategy,
        "size": 128,
        "overlap": 16 if strategy in ("recursive", "fixed") else 0,
        "retriever": retriever,
        "top_k": 3,
        "model": "nomic-embed-text",
    }


@pytest.mark.parametrize(
    ("target", "strategy", "retriever"), itertools.product(FRAMEWORKS, STRATEGIES, RETRIEVERS)
)
def test_every_snippet_parses(target, strategy, retriever):
    source = render(target, values(strategy, retriever))
    tree = ast.parse(source)
    defined = {node.name for node in tree.body if isinstance(node, ast.FunctionDef)}
    assert {"split", "make_retriever"} <= defined


def test_export_uses_the_report():
    report = analyze(CORPUS, tokenizer=RegexTokenizer())
    snippet = export(report, "langchain")
    assert "chunk_size=256" in snippet and "MarkdownHeaderTextSplitter" in snippet
    assert export(report, "yaml").startswith("# RAG configuration generated by ragcompass")
    assert set(TARGETS) == {"yaml", *FRAMEWORKS}
    with pytest.raises(ValueError):
        export(report, "nope")


@pytest.mark.skipif(
    not SNIPPET_PYTHON, reason="set RAGCOMPASS_SNIPPET_PYTHON to an interpreter with the frameworks"
)
@pytest.mark.parametrize(
    ("target", "strategy", "retriever"),
    itertools.product(FRAMEWORKS, ("heading", "recursive", "fixed"), RETRIEVERS),
)
def test_snippets_run(tmp_path, target, strategy, retriever):
    path = tmp_path / f"{target}_{strategy}_{retriever}.py"
    path.write_text(render(target, values(strategy, retriever)), encoding="utf-8")
    done = subprocess.run(
        [SNIPPET_PYTHON, str(RUNNER), target, str(path)], capture_output=True, text=True, timeout=300
    )
    assert done.returncode == 0, done.stdout + done.stderr[-3000:]
